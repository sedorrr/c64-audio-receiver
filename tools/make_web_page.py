#!/usr/bin/env python3
"""
Builds the web page of the firmware from tools/web/index.html: writes src/net/web_page.h (a C string
served by the Pico). Turns the manual docs/HANDBUCH.md into HTML and writes it gzip-compressed into
src/net/help_page.h (GET /hilfe, loaded when the "Hilfe" tab opens).
Run after changing index.html or the manual:  python3 tools/make_web_page.py
"""
import gzip, html as htmlmod, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = lambda *p: os.path.join(ROOT, *p)


# ---------------------------------------------------------------- manual: a small Markdown subset -> HTML
# headings (## / ###), paragraphs, lists (- / 1.), tables, ``` code blocks, `code`, **bold**, *italic*, [links](#x).
# Heading ids are slugs with the prefix "h-" (no clash with the page's own ids); links to #slug are rewritten.
# (Same converter as in the visualizer's make_web_page.py.)
def slug(t):
    t = re.sub(r'`|\*', '', t).lower()
    for a, b in (('ä', 'ae'), ('ö', 'oe'), ('ü', 'ue'), ('ß', 'ss')): t = t.replace(a, b)
    return re.sub(r'[^a-z0-9]+', '-', t).strip('-')

def inline(t):
    codes = []
    def keep(m): codes.append('<code>%s</code>' % htmlmod.escape(m.group(1), quote=False)); return '\0%d\0' % (len(codes) - 1)
    t = re.sub(r'`([^`]+)`', keep, t)
    t = htmlmod.escape(t, quote=False)
    t = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', t)
    t = re.sub(r'(?<![\w*])\*([^*\s][^*]*?)\*(?![\w*])', r'<i>\1</i>', t)
    def link(m):
        href = m.group(2)
        if href.startswith('#'): return '<a href="#h-%s" data-h="%s">%s</a>' % (href[1:], href[1:], m.group(1))
        return '<a href="%s" target=_blank rel=noopener>%s</a>' % (href, m.group(1))
    t = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', link, t)
    return re.sub('\0(\\d+)\0', lambda m: codes[int(m.group(1))], t)

def md_to_html(md):
    out, toc, ids = [], [], set()
    lines = md.split('\n'); i = 0; title = ''
    def cells(l): return [c.strip() for c in l.strip().strip('|').split('|')]
    while i < len(lines):
        l = lines[i]
        if not l.strip(): i += 1; continue
        if l.startswith('```'):
            j = i + 1
            while not lines[j].startswith('```'): j += 1
            out.append('<pre>%s</pre>' % htmlmod.escape('\n'.join(lines[i + 1:j]), quote=False)); i = j + 1; continue
        m = re.match(r'(#{1,3}) (.*)', l)
        if m:
            lvl, text = len(m.group(1)), m.group(2).strip()
            if lvl == 1: title = text; i += 1; continue
            hid = slug(text); assert hid not in ids, 'duplicate heading id ' + hid; ids.add(hid)
            out.append('<h%d id="h-%s">%s</h%d>' % (lvl, hid, inline(text), lvl))
            if lvl == 2: toc.append((hid, text))
            i += 1; continue
        if l.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].startswith('|'): rows.append(cells(lines[i])); i += 1
            body = ''.join('<tr>%s</tr>' % ''.join('<td>%s</td>' % inline(c) for c in r) for r in rows[2:])
            out.append('<div class=tw><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>'
                       % (''.join('<th>%s</th>' % inline(c) for c in rows[0]), body)); continue
        m = re.match(r'(- |\d+\. )', l)
        if m:
            tag = 'ul' if l.startswith('- ') else 'ol'; items = []
            while i < len(lines) and re.match(r'(- |\d+\. )', lines[i]):
                item = re.sub(r'^(- |\d+\. )', '', lines[i]); i += 1
                while i < len(lines) and lines[i].startswith('  ') and lines[i].strip(): item += ' ' + lines[i].strip(); i += 1
                items.append('<li>%s</li>' % inline(item))
            out.append('<%s>%s</%s>' % (tag, ''.join(items), tag)); continue
        para = []
        while i < len(lines) and lines[i].strip() and not re.match(r'(#|\||```|- |\d+\. )', lines[i]): para.append(lines[i].strip()); i += 1
        out.append('<p>%s</p>' % inline(' '.join(para)))
    for h in re.findall(r'data-h="([^"]+)"', ''.join(out)): assert h in ids, 'manual: link to unknown section #' + h
    nav = '<nav class=htoc><b>Inhalt</b><ol>%s</ol></nav>' % ''.join(
        '<li><a href="#h-%s" data-h="%s">%s</a></li>' % (h, h, inline(t)) for h, t in toc)
    body = ''.join(out); k = body.find('<h2 id=')                 # contents after the introduction
    return '<h2 class=htitle>%s</h2>%s%s%s' % (inline(title), body[:k], nav, body[k:]), ids

help_html, help_ids = md_to_html(open(src('docs', 'HANDBUCH.md'), encoding='utf-8').read())

html = open(src('tools', 'web', 'index.html'), encoding='utf-8').read()
for h in re.findall(r"help\('([^']+)'\)", html):                  # context links in the tabs must hit a section
    assert h in help_ids, 'index.html: help link to unknown section ' + h
lines = ['/* Generated by tools/make_web_page.py from tools/web/index.html - do not edit by hand. */',
         '#pragma once', 'static const char WEB_PAGE[] =']
data = html.encode('utf-8')
for i in range(0, len(data), 100):
    chunk = data[i:i+100]
    s = ''.join('\\\\' if b == 92 else '\\"' if b == 34 else chr(b) if 32 <= b < 127 else '\\%03o' % b for b in chunk)
    lines.append('"%s"' % s)
lines[-1] += ';'
open(src('src', 'net', 'web_page.h'), 'w').write('\n'.join(lines) + '\n')
gz = gzip.compress(help_html.encode('utf-8'), 9, mtime=0)
lines = ['/* Generated by tools/make_web_page.py from docs/HANDBUCH.md - do not edit by hand. */',
         '/* The manual as HTML fragment, gzip-compressed (served with Content-Encoding: gzip). */',
         '#pragma once', '#define HELP_GZ_LEN %d' % len(gz), 'static const unsigned char HELP_GZ[HELP_GZ_LEN] = {']
for i in range(0, len(gz), 24): lines.append('    ' + ','.join(str(b) for b in gz[i:i+24]) + ',')
lines.append('};')
open(src('src', 'net', 'help_page.h'), 'w').write('\n'.join(lines) + '\n')
print('web page: %d bytes; manual: %d bytes, %d gzip' % (len(data), len(help_html.encode('utf-8')), len(gz)))
